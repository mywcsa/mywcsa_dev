-- MyWCSA GovApps · ServiceDesk / e-Innovation / BiT / ICT Control Centre
-- The live service-role API is the only entry point; no client access to these tables.
-- Initial command managers MUST be explicitly authorised. This migration grants none.
create table if not exists public.govapps_control_operators (
  email text primary key check (email=lower(trim(email)) and email like '%@wcsports.co.za'),
  role text not null check(role in ('director','einnovation','servicedesk','bit','ict','viewer')),
  active boolean not null default true,
  granted_by text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.govapps_control_requests (
  id bigint generated by default as identity primary key,
  kind text not null check(kind in ('support','staff_account','business_partner','access','device','software','other')),
  title text not null check(char_length(trim(title)) between 5 and 140),
  description text not null check(char_length(trim(description)) between 10 and 4000),
  target_email text,
  wcsa_id text,
  priority text not null default 'normal' check(priority in ('low','normal','high','critical')),
  team text not null check(team in ('servicedesk','einnovation','bit','ict')),
  status text not null default 'new' check(status in ('new','triage','assigned','awaiting_approval','approved','in_progress','resolved','rejected','closed')),
  assignee text,
  external_reference text,
  requested_by text not null,
  updated_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists govapps_control_requests_queue on public.govapps_control_requests(team,status,created_at desc);
create index if not exists govapps_control_requests_owner on public.govapps_control_requests(requested_by,created_at desc);

create table if not exists public.govapps_control_allocations (
  id bigint generated by default as identity primary key,
  category text not null check(category in ('device','software','licence','access')),
  item_name text not null check(char_length(trim(item_name)) between 3 and 140),
  asset_tag text,
  recipient_email text not null,
  team text not null check(team in ('ict','bit','einnovation')),
  status text not null default 'allocated' check(status in ('allocated','returned','retired','revoked')),
  note text not null default '',
  reference_request_id bigint references public.govapps_control_requests(id),
  assigned_by text not null,
  updated_by text,
  assigned_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint govapps_allocations_note_len check(char_length(note)<=1500)
);
create index if not exists govapps_control_allocations_recipient on public.govapps_control_allocations(lower(recipient_email));

create table if not exists public.govapps_control_audit (
  id bigint generated by default as identity primary key,
  actor_email text not null,
  action text not null,
  request_id bigint references public.govapps_control_requests(id),
  allocation_id bigint references public.govapps_control_allocations(id),
  detail jsonb not null default '{}'::jsonb,
  happened_at timestamptz not null default now()
);
create index if not exists govapps_control_audit_recent on public.govapps_control_audit(happened_at desc);
alter table public.govapps_control_operators enable row level security;
alter table public.govapps_control_requests enable row level security;
alter table public.govapps_control_allocations enable row level security;
alter table public.govapps_control_audit enable row level security;
revoke all on public.govapps_control_operators,public.govapps_control_requests,public.govapps_control_allocations,public.govapps_control_audit from public,anon,authenticated;
grant select,insert,update on public.govapps_control_operators,public.govapps_control_requests,public.govapps_control_allocations to service_role;
grant select,insert on public.govapps_control_audit to service_role;
grant usage,select on all sequences in schema public to service_role;

-- All mutating functions require an active recognised operator and are executable by service_role only.
create or replace function public.govapps_control_create_request(
 p_actor text,p_kind text,p_title text,p_description text,p_target_email text default null,p_wcsa_id text default null,p_priority text default 'normal'
) returns public.govapps_control_requests language plpgsql security definer set search_path='' as $$
declare a text; r public.govapps_control_requests; routed text;
begin
  select role into a from public.govapps_control_operators where email=lower(trim(p_actor)) and active;
  if a is null or a='viewer' then raise exception 'Not authorised' using errcode='42501'; end if;
  if p_kind not in ('support','staff_account','business_partner','access','device','software','other') then raise exception 'Unknown request kind' using errcode='22023'; end if;
  routed:=case when p_kind='device' then 'ict' when p_kind='software' then 'bit' when p_kind in ('staff_account','business_partner','access') then 'einnovation' else 'servicedesk' end;
  insert into public.govapps_control_requests(kind,title,description,target_email,wcsa_id,priority,team,requested_by)
  values(p_kind,trim(p_title),trim(p_description),nullif(lower(trim(p_target_email)),''),nullif(trim(p_wcsa_id),''),p_priority,routed,lower(trim(p_actor)))
  returning * into r;
  insert into public.govapps_control_audit(actor_email,action,request_id,detail)
  values(lower(trim(p_actor)),'request_created',r.id,jsonb_build_object('kind',r.kind,'team',r.team,'status',r.status));
  return r;
end $$;

create or replace function public.govapps_control_update_request(
 p_actor text,p_request_id bigint,p_status text,p_team text,p_assignee text default null,p_external_reference text default null
) returns public.govapps_control_requests language plpgsql security definer set search_path='' as $$
declare role_name text; old public.govapps_control_requests; result public.govapps_control_requests;
begin
  select role into role_name from public.govapps_control_operators where email=lower(trim(p_actor)) and active;
  if role_name is null or role_name='viewer' then raise exception 'Not authorised' using errcode='42501'; end if;
  select * into old from public.govapps_control_requests where id=p_request_id for update;
  if not found then raise exception 'Request not found' using errcode='22023'; end if;
  if role_name not in ('director','einnovation','servicedesk') and role_name<>old.team then raise exception 'Outside assigned team' using errcode='42501'; end if;
  if p_status in ('approved','rejected') and role_name not in ('director','einnovation') then raise exception 'Approval authority required' using errcode='42501'; end if;
  if p_team<>old.team and role_name not in ('director','einnovation','servicedesk') then raise exception 'Routing authority required' using errcode='42501'; end if;
  if p_status in ('resolved','closed') and old.kind in ('staff_account','business_partner','access') and
    (role_name not in ('director','einnovation') or length(trim(coalesce(p_external_reference,old.external_reference,'')))<4)
  then raise exception 'Authorised completion and an external confirmation reference are required' using errcode='42501'; end if;
  update public.govapps_control_requests
  set status=p_status,team=p_team,assignee=nullif(lower(trim(p_assignee)),''),
      external_reference=nullif(trim(p_external_reference),''),
      updated_by=lower(trim(p_actor)),updated_at=now()
  where id=p_request_id returning * into result;
  insert into public.govapps_control_audit(actor_email,action,request_id,detail)
  values(lower(trim(p_actor)),'request_updated',p_request_id,
    jsonb_build_object('previous_status',old.status,'new_status',result.status,'previous_team',old.team,'new_team',result.team,'assignee',result.assignee,'reference',result.external_reference));
  return result;
end $$;

create or replace function public.govapps_control_create_allocation(
 p_actor text,p_category text,p_item_name text,p_recipient_email text,p_asset_tag text default null,p_note text default '',p_request_id bigint default null
) returns public.govapps_control_allocations language plpgsql security definer set search_path='' as $$
declare role_name text; routed text; result public.govapps_control_allocations;
begin
  select role into role_name from public.govapps_control_operators where email=lower(trim(p_actor)) and active;
  routed:=case when p_category='device' then 'ict' when p_category in ('software','licence') then 'bit' when p_category='access' then 'einnovation' else null end;
  if routed is null then raise exception 'Unknown allocation type' using errcode='22023'; end if;
  if role_name not in ('director','einnovation',routed) then raise exception 'Allocation permission denied' using errcode='42501'; end if;
  if p_request_id is not null and not exists (select 1 from public.govapps_control_requests where id=p_request_id) then
    raise exception 'Request reference not found' using errcode='22023'; end if;
  insert into public.govapps_control_allocations(category,item_name,recipient_email,team,asset_tag,note,reference_request_id,assigned_by)
  values(p_category,trim(p_item_name),lower(trim(p_recipient_email)),routed,nullif(trim(p_asset_tag),''),trim(p_note),p_request_id,lower(trim(p_actor)))
  returning * into result;
  insert into public.govapps_control_audit(actor_email,action,allocation_id,detail)
  values(lower(trim(p_actor)),'allocation_created',result.id,jsonb_build_object('category',result.category,'item',result.item_name,'recipient',result.recipient_email));
  return result;
end $$;

create or replace function public.govapps_control_update_allocation(
 p_actor text,p_id bigint,p_status text
) returns public.govapps_control_allocations language plpgsql security definer set search_path='' as $$
declare role_name text; old public.govapps_control_allocations; result public.govapps_control_allocations;
begin
  select role into role_name from public.govapps_control_operators where email=lower(trim(p_actor)) and active;
  select * into old from public.govapps_control_allocations where id=p_id for update;
  if not found then raise exception 'Allocation not found' using errcode='22023'; end if;
  if role_name not in ('director','einnovation',old.team) then raise exception 'Not authorised' using errcode='42501'; end if;
  update public.govapps_control_allocations set status=p_status,updated_by=lower(trim(p_actor)),updated_at=now()
  where id=p_id returning * into result;
  insert into public.govapps_control_audit(actor_email,action,allocation_id,detail)
  values(lower(trim(p_actor)),'allocation_updated',p_id,jsonb_build_object('previous_status',old.status,'new_status',result.status));
  return result;
end $$;

create or replace function public.govapps_control_set_operator(
 p_actor text,p_email text,p_role text,p_active boolean
) returns public.govapps_control_operators language plpgsql security definer set search_path='' as $$
declare role_name text; result public.govapps_control_operators;
begin
  select role into role_name from public.govapps_control_operators where email=lower(trim(p_actor)) and active;
  if role_name<>'director' then raise exception 'Director authority required' using errcode='42501'; end if;
  if p_email !~* '^[^[:space:]@]+@wcsports[.]co[.]za$' then raise exception 'Use a verified WCSA email' using errcode='22023'; end if;
  if p_role not in ('director','einnovation','servicedesk','bit','ict','viewer') then raise exception 'Invalid operator role' using errcode='22023'; end if;
  if lower(trim(p_email))=lower(trim(p_actor)) and not p_active then raise exception 'Cannot deactivate own control account' using errcode='42501'; end if;
  insert into public.govapps_control_operators(email,role,active,granted_by)
  values(lower(trim(p_email)),p_role,p_active,lower(trim(p_actor)))
  on conflict(email) do update set role=excluded.role,active=excluded.active,granted_by=excluded.granted_by,updated_at=now()
  returning * into result;
  insert into public.govapps_control_audit(actor_email,action,detail)
  values(lower(trim(p_actor)),'operator_changed',jsonb_build_object('operator',result.email,'role',result.role,'active',result.active));
  return result;
end $$;

